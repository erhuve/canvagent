import assert from 'node:assert/strict';
import { existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, realpathSync, renameSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test, type TestContext } from 'node:test';
import { MAX_MANAGEMENT_BYTES, MAX_MANAGEMENT_ENTRIES, WorkspaceFiles } from '../src/server/workspace-files.ts';
import { createWorkspaceHost } from '../src/server/workspaces.ts';

function fixture(t: TestContext) {
  const directory = realpathSync(mkdtempSync(join(tmpdir(), 'canvagent-file-management-')));
  const workspace = join(directory, 'workspace'), trashDirectory = join(directory, 'recovery');
  mkdirSync(workspace);
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  return { directory, workspace, trashDirectory, files: new WorkspaceFiles(workspace, { trashDirectory }) };
}
const status = (expected: number) => (error: any) => error?.status === expected;

test('file management creates files and folders exclusively and validates workspace paths', async t => {
  const f = fixture(t);
  assert.deepEqual(await f.files.create('content', 'directory'), { path: 'content', kind: 'directory' });
  assert.deepEqual(await f.files.create('content/new.md', 'file'), { path: 'content/new.md', kind: 'file' });
  assert.equal(readFileSync(join(f.workspace, 'content', 'new.md'), 'utf8'), '');
  writeFileSync(join(f.workspace, 'content', 'new.md'), 'preserve me');
  await assert.rejects(f.files.create('content/new.md', 'file'), status(409));
  await assert.rejects(f.files.create('content/new.md', 'directory'), status(409));
  assert.equal(readFileSync(join(f.workspace, 'content', 'new.md'), 'utf8'), 'preserve me');
  for (const path of ['', '.', '..', '../escape', '/tmp/escape', 'C:\\escape', 'C:escape', 'nested\\escape']) await assert.rejects(f.files.create(path, 'file'), status(400));
  for (const path of ['.git', '.GIT/config', 'content/.git']) await assert.rejects(f.files.create(path, 'directory'), status(403));
  await assert.rejects(f.files.create('missing/new.md', 'file'), status(404));
  const concurrent = await Promise.allSettled([f.files.create('same.md', 'file'), f.files.create('same.md', 'file')]);
  assert.equal(concurrent.filter(result => result.status === 'fulfilled').length, 1);
  assert.equal((concurrent.find(result => result.status === 'rejected') as PromiseRejectedResult).reason.status, 409);
});

test('item revisions count a bounded subtree and detect binary or descendant changes', async t => {
  const f = fixture(t);
  mkdirSync(join(f.workspace, 'content', 'images'), { recursive: true });
  writeFileSync(join(f.workspace, 'content', 'post.md'), 'hello');
  writeFileSync(join(f.workspace, 'content', 'images', 'picture.bin'), Buffer.from([0, 255, 8]));
  const info = await f.files.info('content');
  assert.deepEqual({ ...info, revision: 'token' }, { path: 'content', name: 'content', kind: 'directory', revision: 'token', entries: 3, size: 8 });
  assert.match(info.revision, /^[a-f0-9]{64}$/);
  assert.equal((await f.files.info('content')).revision, info.revision);
  writeFileSync(join(f.workspace, 'content', 'images', 'picture.bin'), Buffer.from([0, 254, 8]));
  await assert.rejects(f.files.move('content', 'renamed', info.revision), status(409));
  await assert.rejects(f.files.remove('content', info.revision), status(409));
  assert.equal(existsSync(join(f.workspace, 'content', 'post.md')), true);
  const binary = await f.files.info('content/images/picture.bin');
  assert.equal(binary.size, 3); assert.equal(binary.entries, 0);
  await f.files.move(binary.path, 'content/images/renamed.bin', binary.revision);
  assert.deepEqual(readFileSync(join(f.workspace, 'content', 'images', 'renamed.bin')), Buffer.from([0, 254, 8]));
});

test('renaming files and folders never replaces an existing destination and serializes saves', async t => {
  const f = fixture(t);
  mkdirSync(join(f.workspace, 'content'));
  writeFileSync(join(f.workspace, 'content', 'post.md'), 'before');
  writeFileSync(join(f.workspace, 'occupied.md'), 'occupied');
  const opened = await f.files.read('content/post.md');
  const item = await f.files.info(opened.path);
  await assert.rejects(f.files.move(item.path, 'occupied.md', item.revision), status(409));
  assert.equal(readFileSync(join(f.workspace, 'occupied.md'), 'utf8'), 'occupied');
  const saved = f.files.write(opened.path, 'saved before rename', opened.revision);
  const staleMove = f.files.move(opened.path, 'new.md', item.revision);
  await saved;
  await assert.rejects(staleMove, status(409));
  assert.equal(readFileSync(join(f.workspace, 'content', 'post.md'), 'utf8'), 'saved before rename');
  const directory = await f.files.info('content');
  await assert.rejects(f.files.move('content', 'content/nested', directory.revision), status(400));
  assert.deepEqual(await f.files.move('content', 'renamed', directory.revision), { path: 'renamed', previousPath: 'content', kind: 'directory' });
  assert.equal(readFileSync(join(f.workspace, 'renamed', 'post.md'), 'utf8'), 'saved before rename');
  await assert.rejects(f.files.move('', 'root', directory.revision), status(400));
  await assert.rejects(f.files.move('renamed', 'renamed-again', ''), status(400));
});

test('managed recovery is durable, preserves binary and linked descendants, and restores exclusively', async t => {
  const f = fixture(t);
  mkdirSync(join(f.workspace, 'content', 'empty'), { recursive: true });
  writeFileSync(join(f.workspace, 'content', 'image.bin'), Buffer.from([0, 255, 8]));
  writeFileSync(join(f.directory, 'outside.txt'), 'outside stays');
  symlinkSync(join(f.directory, 'outside.txt'), join(f.workspace, 'content', 'outside-link'));
  const original = await f.files.info('content');
  const removed = await f.files.remove('content', original.revision);
  assert.equal(removed.deleted, true); assert.equal(removed.trashed, true);
  assert.equal(existsSync(join(f.workspace, 'content')), false);
  assert.equal(readFileSync(join(f.directory, 'outside.txt'), 'utf8'), 'outside stays');
  assert.deepEqual(readdirSync(f.trashDirectory), [removed.trashId]);
  const restarted = new WorkspaceFiles(f.workspace, { trashDirectory: f.trashDirectory });
  await restarted.create('content', 'directory');
  await assert.rejects(restarted.restore(removed.trashId), status(409));
  rmSync(join(f.workspace, 'content'), { recursive: true });
  assert.deepEqual(await restarted.restore(removed.trashId), { path: 'content', kind: 'directory' });
  assert.deepEqual(readFileSync(join(f.workspace, 'content', 'image.bin')), Buffer.from([0, 255, 8]));
  assert.equal(lstatSync(join(f.workspace, 'content', 'outside-link')).isSymbolicLink(), true);
  assert.equal((await restarted.info('content')).revision, original.revision);
  assert.deepEqual(readdirSync(f.trashDirectory), []);
  await assert.rejects(restarted.restore(removed.trashId), status(404));
  await assert.rejects(restarted.restore('../escape'), status(400));
});

test('recovery refuses changed stored content, changed parent locations and forged project IDs', async t => {
  const f = fixture(t);
  mkdirSync(join(f.workspace, 'content'));
  writeFileSync(join(f.workspace, 'content', 'post.md'), 'before');
  const info = await f.files.info('content/post.md');
  const removed = await f.files.remove(info.path, info.revision);
  writeFileSync(join(f.trashDirectory, removed.trashId, 'item'), 'changed in recovery');
  await assert.rejects(f.files.restore(removed.trashId), status(409));
  assert.equal(existsSync(join(f.workspace, info.path)), false);
  writeFileSync(join(f.workspace, 'content', 'post.md'), 'second');
  const next = await f.files.info('content/post.md');
  const removedAgain = await f.files.remove(next.path, next.revision);
  renameSync(join(f.workspace, 'content'), join(f.workspace, 'moved'));
  mkdirSync(join(f.directory, 'outside'));
  symlinkSync(join(f.directory, 'outside'), join(f.workspace, 'content'));
  await assert.rejects(f.files.restore(removedAgain.trashId), status(403));
  assert.equal(existsSync(join(f.directory, 'outside', 'post.md')), false);
  const foreign = new WorkspaceFiles(f.workspace, { trashDirectory: join(f.directory, 'foreign-recovery') });
  await assert.rejects(foreign.restore(removedAgain.trashId), status(404));
});

test('mutations reject symbolic link paths, nested Git repositories, recovery storage and oversized items', async t => {
  const f = fixture(t);
  mkdirSync(join(f.workspace, 'safe'));
  writeFileSync(join(f.workspace, 'safe', 'file.txt'), 'safe');
  symlinkSync(join(f.workspace, 'safe'), join(f.workspace, 'safe-link'));
  symlinkSync(join(f.workspace, 'safe', 'file.txt'), join(f.workspace, 'file-link'));
  for (const path of ['safe-link', 'file-link', 'safe-link/file.txt']) await assert.rejects(f.files.info(path), status(403));
  await assert.rejects(f.files.create('safe-link/new.txt', 'file'), status(403));
  mkdirSync(join(f.workspace, 'nested', '.git'), { recursive: true });
  writeFileSync(join(f.workspace, 'nested', '.git', 'config'), 'preserve');
  await assert.rejects(f.files.info('nested'), status(403));
  const protectedFiles = new WorkspaceFiles(f.workspace, { trashDirectory: join(f.workspace, '.canvagent', 'file-trash') });
  mkdirSync(join(f.workspace, '.canvagent', 'file-trash'), { recursive: true });
  await assert.rejects(protectedFiles.info('.canvagent'), status(403));
  await assert.rejects(protectedFiles.create('.canvagent/file-trash/fake', 'file'), status(403));
  const appFiles = new WorkspaceFiles(f.workspace, { trashDirectory: join(f.directory, 'trash'), protectedDirectory: join(f.workspace, 'app', 'data') });
  mkdirSync(join(f.workspace, 'app', 'data'), { recursive: true });
  writeFileSync(join(f.workspace, 'app', 'data', 'store.sqlite'), 'application data');
  await assert.rejects(appFiles.info('app'), status(403));
  await assert.rejects(appFiles.info('app/data/store.sqlite'), status(403));
  await assert.rejects(appFiles.create('app/data/new.txt', 'file'), status(403));
  assert.equal((await appFiles.create('app/ordinary-file.txt', 'file')).path, 'app/ordinary-file.txt');
  writeFileSync(join(f.workspace, 'large.bin'), Buffer.alloc(MAX_MANAGEMENT_BYTES + 1));
  await assert.rejects(f.files.info('large.bin'), status(413));
  mkdirSync(join(f.workspace, 'many'));
  for (let index = 0; index <= MAX_MANAGEMENT_ENTRIES; index++) writeFileSync(join(f.workspace, 'many', `${index}.txt`), '');
  await assert.rejects(f.files.info('many'), status(413));
});

test('file management HTTP routes require project authentication, validate tokens and keep recovery project scoped', async t => {
  const f = fixture(t);
  const host = createWorkspaceHost({ workspace: f.workspace, dataRoot: join(f.directory, 'data'), port: 0 });
  t.after(() => host.close());
  await new Promise<void>(done => host.server.listen(0, '127.0.0.1', done));
  const address = host.server.address(); assert.ok(address && typeof address === 'object');
  const base = `http://127.0.0.1:${address.port}`, firstPath = host.projectPath(host.initialProjectId);
  const bootstrap = await fetch(`${base}${firstPath}api/state`);
  const cookie = bootstrap.headers.get('set-cookie')!.split(';')[0];
  const post = (route: string, body: unknown, auth = cookie, prefix = firstPath) => fetch(`${base}${prefix}api/files/${route}`, { method: 'POST', headers: { cookie: auth, 'content-type': 'application/json' }, body: JSON.stringify(body) });
  assert.equal((await post('create', { path: 'blocked', kind: 'file' }, '')).status, 401);
  assert.equal((await fetch(`${base}${firstPath}api/files/info?path=blocked`)).status, 401);
  assert.equal((await post('create', { path: 'content', kind: 'directory' })).status, 200);
  assert.equal((await post('create', { path: 'content/new.md', kind: 'file' })).status, 200);
  assert.equal((await post('create', { path: 'content/new.md', kind: 'file' })).status, 409);
  assert.equal((await post('create', { path: '.git/config', kind: 'file' })).status, 403);
  const info = await (await fetch(`${base}${firstPath}api/files/info?path=content`, { headers: { cookie } })).json() as any;
  assert.equal(info.kind, 'directory'); assert.equal(info.entries, 1);
  writeFileSync(join(f.workspace, 'content', 'new.md'), 'new disk content');
  assert.equal((await post('delete', { path: 'content', revision: info.revision })).status, 409);
  const fresh = await (await fetch(`${base}${firstPath}api/files/info?path=content`, { headers: { cookie } })).json() as any;
  assert.equal((await post('rename', { path: 'content', newPath: 'posts', revision: fresh.revision })).status, 200);
  const moved = await (await fetch(`${base}${firstPath}api/files/info?path=posts`, { headers: { cookie } })).json() as any;
  const deleted = await post('delete', { path: 'posts', revision: moved.revision });
  assert.equal(deleted.status, 200);
  const recovery = await deleted.json() as any; assert.equal(recovery.trashed, true);
  const root = await fetch(`${base}/api/projects`), hostCookie = root.headers.get('set-cookie')!.split(';')[0];
  const other = join(f.directory, 'other'); mkdirSync(other);
  const added = await fetch(`${base}/api/projects`, { method: 'POST', headers: { cookie: hostCookie, 'content-type': 'application/json' }, body: JSON.stringify({ workspace: other }) });
  const project = await added.json() as any;
  const otherBootstrap = await fetch(`${base}${project.path}api/state`), otherCookie = otherBootstrap.headers.get('set-cookie')!.split(';')[0];
  assert.equal((await post('restore', { trashId: recovery.trashId }, otherCookie, project.path)).status, 404);
  assert.equal((await post('restore', { trashId: recovery.trashId })).status, 200);
  assert.equal(readFileSync(join(f.workspace, 'posts', 'new.md'), 'utf8'), 'new disk content');
  assert.equal((await post('delete', { path: 'posts' })).status, 400);
  assert.equal((await post('rename', { path: 'posts', newPath: 'other', revision: 'invalid' })).status, 400);
  const badOrigin = await fetch(`${base}${firstPath}api/files/create`, { method: 'POST', headers: { cookie, origin: 'https://example.com', 'content-type': 'application/json' }, body: JSON.stringify({ path: 'blocked', kind: 'file' }) });
  assert.equal(badOrigin.status, 403);
});
